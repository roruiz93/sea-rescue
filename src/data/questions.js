// ── Helper functions ──────────────────────────────────────────────────────────

/**
 * Returns N random questions filtered by difficulty.
 * @param {string} difficulty  'easy' | 'medium' | 'hard' | 'any'
 * @param {number} count
 */
export function getRandomQuestions(difficulty = 'any', count = 5) {
  const pool = difficulty === 'any'
    ? QUESTIONS
    : QUESTIONS.filter(q => q.difficulty === difficulty);

  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}

/** Returns a single random question. */
export function getRandomQuestion(difficulty = 'any') {
  return getRandomQuestions(difficulty, 1)[0];
}

/** Returns all questions for a given category. */
export function getByCategory(category) {
  return QUESTIONS.filter(q => q.category === category);
}
